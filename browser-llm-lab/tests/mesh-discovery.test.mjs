test('independent Cypher Go crypto vector verifies exact native signature, recovery ID, Keccak domain and node identity', () => {
  // Generated by Cypher crypto.Sign/crypto.VerifySignature, not by noble. Fixed
  // public test scalar=1. The reproduction source and output are retained in
  // relay/evidence/discovery/; private production/native keys were never read.
  const envelope = meshAdvertisement(identity);
  const signatureHex = 'ac0a3de557837c6a81d01ab8dfcf32cafd5abeaa3ff37283380b67448d2596b57b3d8a42d525c4ea2cc076749bd65fe5649dd07a42bdc3c447aedf282913cb1800';
  assert.equal(envelope.signatureHex, signatureHex, 'deterministic Go and noble signatures match byte for byte');
  const result = verifyMeshAdvertisement({ ...envelope, signatureHex }, network, now);
  assert.equal(result.nodeId, 'c0a6c424ac7157ae408398df7e5f4552091a69125d5dfcb7b8c2659029395bdf');
  assert.throws(() => verifyMeshAdvertisement({ ...envelope, signatureHex: signatureHex.slice(0, -2) + '01' }, network, now), errorCode('invalid_signature'));
});

test('native advertisements authenticate complete signed bytes and reject forged signatures and invalid curve points', () => {
  const env = meshAdvertisement(identity), record = verifyMeshAdvertisement(env, network, now);
  assert.equal(record.publicKey, identity.publicKeyHex);
  const changed = { ...decode(env), expiresAt: now + 110000 };
  assert.throws(() => verifyMeshAdvertisement({ ...env, payloadBase64: Buffer.from(JSON.stringify(changed)).toString('base64') }, network, now), errorCode('invalid_signature'));
  assert.throws(() => verifyMeshAdvertisement(meshAdvertisement(identity, { enode: other.enode }), network, now), errorCode('invalid_signature'));
  assert.throws(() => verifyMeshAdvertisement(meshAdvertisement(identity, { enode: `enode://${'00'.repeat(64)}` }), network, now), errorCode('invalid_signature'));
  const wrongDomain = signDiscoveryRaw(record.raw, identity, DISCOVERY_DOMAINS.endpoint);
  assert.throws(() => verifyMeshAdvertisement(wrongDomain, network, now), errorCode('invalid_signature'));
  assert.throws(() => verifyMeshAdvertisement(signDiscoveryRaw(record.raw, identity, DISCOVERY_DOMAINS.advertisement.slice(0, -1)), network, now), errorCode('invalid_signature'));
  // High-S malleation remains mathematically valid ECDSA but native verification
  // requires low-S. Toggle recovery parity alongside n-S and still reject it.
  const order = 0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e8cd0364141n;
  const s = BigInt('0x' + env.signatureHex.slice(64, 128));
  const signatureHex = env.signatureHex.slice(0, 64) + (order - s).toString(16).padStart(64, '0') + (env.signatureHex.endsWith('00') ? '01' : '00');
  assert.throws(() => verifyMeshAdvertisement({ ...env, signatureHex }, network, now), errorCode('invalid_signature'));
});

