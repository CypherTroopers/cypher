test('signed SDP and ICE bind sender generation and recipient; tampered recovery/signature and future/stale records fail', () => {
  const record = browser(), envelope = signSignal(signalPayload(), identity), verified = verifySignal(envelope, record, network, now);
  assert.equal(verified.to, other.peerId); assert.equal(verified.value, signalPayload().value);
  assert.throws(() => verifySignal(envelope, browser({ sessionId: '44'.repeat(16) }), network, now), errorCode('wrong_session'));
  assert.throws(() => verifySignal(envelope, record, network, now + 30000), errorCode('stale_advertisement'));
  assert.throws(() => verifySignal(envelope, browser({}, other), network, now), errorCode('wrong_session'));
  for (const value of [null, { candidate: 'candidate:1 1 udp 1 1.2.3.4 9999 typ host', sdpMid: '0', sdpMLineIndex: 0, usernameFragment: 'ufrag' }]) {
    const ice = signSignal(signalPayload({ type: 'ice', value }), identity); assert.deepEqual(verifySignal(ice, record, network, now).value, value);
  }
  const tampered = { ...decode(envelope), to: 'ee'.repeat(16) };
  assert.throws(() => verifySignal({ ...envelope, payloadBase64: Buffer.from(JSON.stringify(tampered)).toString('base64') }, record, network, now), errorCode('invalid_signature'));
});

