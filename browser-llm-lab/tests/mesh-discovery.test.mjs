test('RAM endpoint cache rejects sequence rollback, same-sequence mutation and old-process replay', () => {
  let clock = now; const cache = new EndpointCache(network, { now: () => clock });
  const first = endpointAdvertisement(); const record = cache.add(first); assert.equal(cache.add(first), record);
  cache.add(endpointAdvertisement(identity, { sequence: 2, issuedAt: now + 1 }));
  assert.throws(() => cache.add(first), errorCode('sequence_rollback'));
  assert.throws(() => cache.add(endpointAdvertisement(identity, { sequence: 2, issuedAt: now + 1, gatewayOrigin: 'https://other.example.org' })), errorCode('sequence_rollback'));
  const restarted = endpointAdvertisement(identity, { bootId: '77'.repeat(16), sequence: 1, issuedAt: now + 2 }); cache.add(restarted);
  assert.throws(() => cache.add(endpointAdvertisement(identity, { sequence: 3, issuedAt: now + 3 })), errorCode('sequence_rollback'));
  assert.throws(() => cache.add(endpointAdvertisement(identity, { bootId: '88'.repeat(16), issuedAt: now + 1 })), errorCode('sequence_rollback'));
  assert.equal(cache.values().length, 1); clock = now + 120000; assert.equal(cache.values().length, 0); assert.equal(cache.get(identity.nodeId), undefined);
  clock += 10000; cache.prune(); assert.equal(cache.records.size, 0);
});

test('cache cap rejects new identities without evicting current routes and bounds restart tombstones', () => {
  const cache = new EndpointCache(network, { now: () => now, maxEntries: 1 }); cache.add(endpointAdvertisement());
  assert.throws(() => cache.add(endpointAdvertisement(other)), errorCode('resource_limit')); assert.equal(cache.get(identity.nodeId).sourceId, 'common-a');
  for (let i = 1; i <= 8; i++) cache.add(endpointAdvertisement(identity, { bootId: i.toString(16).padStart(32, '0'), issuedAt: now + i }));
  assert.throws(() => cache.add(endpointAdvertisement(identity, { bootId: '99'.repeat(16), issuedAt: now + 9 })), errorCode('resource_limit'));
  assert.equal(cache.records.get(identity.nodeId).retired.size, 8);
});

