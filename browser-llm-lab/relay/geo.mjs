// Historical API name; these are published display anchors, not computed
// geometric centroids or measurements of a person's actual coordinates.
export function countryCentroid(code) {
  if (typeof code !== 'string' || !/^[A-Z]{2}$/.test(code) || !Object.hasOwn(countries, code)) return null;
  const [label, lat, lon] = countries[code];
  return { countryCode: code, label, lat, lon, accuracy: 'country', source: 'cloudflare' };
}
